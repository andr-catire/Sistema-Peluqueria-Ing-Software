-- Necesaria para combinar igualdad (agenda_id) y solapamiento de rangos en una sola restricción.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE citas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agenda_id   BIGINT        NOT NULL REFERENCES agendas (id),
    cliente_id  BIGINT        NOT NULL REFERENCES clientes (id),
    servicio_id BIGINT        NOT NULL REFERENCES servicios (id),
    hora_inicio TIME          NOT NULL,
    hora_fin    TIME          NOT NULL,
    costo       NUMERIC(10,2) NOT NULL,
    estado      VARCHAR(20)   NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT ck_citas_rango  CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_citas_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA')),
    -- Garantía real anti doble reserva: en una misma agenda (estilista y día) dos citas no canceladas
    -- no pueden solaparse. Una que termina a las 11:00 y otra que empieza a las 11:00 no se solapan.
    CONSTRAINT ex_citas_sin_solape EXCLUDE USING gist (
        agenda_id WITH =,
        (tsrange(DATE '2000-01-01' + hora_inicio, DATE '2000-01-01' + hora_fin)) WITH &&
    ) WHERE (estado <> 'CANCELADA')
);

CREATE INDEX ix_citas_cliente ON citas (cliente_id);
