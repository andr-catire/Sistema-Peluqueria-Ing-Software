CREATE TABLE servicios (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(120) NOT NULL,
    descripcion      TEXT,
    costo            NUMERIC(10, 2) NOT NULL CHECK (costo >= 0),
    duracion_minutos INTEGER NOT NULL CHECK (duracion_minutos > 0),
    activo           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE personal (
    id BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE
);

CREATE TABLE personal_servicios (
    personal_id BIGINT NOT NULL REFERENCES personal(id) ON DELETE CASCADE,
    servicio_id BIGINT NOT NULL REFERENCES servicios(id),
    PRIMARY KEY (personal_id, servicio_id)
);

CREATE TABLE clientes (
    id                    BIGINT PRIMARY KEY REFERENCES usuarios(id) ON DELETE CASCADE,
    cedula                VARCHAR(20) NOT NULL UNIQUE,
    telefono              VARCHAR(30) NOT NULL,
    estilista_habitual_id BIGINT REFERENCES personal(id)
);

CREATE TABLE citas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha        DATE NOT NULL,
    hora         TIME NOT NULL,
    cliente_id   BIGINT NOT NULL REFERENCES clientes(id),
    estilista_id BIGINT NOT NULL REFERENCES personal(id),
    estado       VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                 CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA'))
);

CREATE TABLE asistencias (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id            BIGINT NOT NULL UNIQUE REFERENCES citas(id),
    cliente_confirmo   BOOLEAN NOT NULL DEFAULT FALSE,
    estilista_confirmo BOOLEAN NOT NULL DEFAULT FALSE
);