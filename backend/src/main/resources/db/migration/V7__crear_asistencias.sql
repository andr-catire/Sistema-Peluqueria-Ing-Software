CREATE TABLE asistencias (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personal_id  BIGINT NOT NULL REFERENCES personal (id),
    fecha        DATE   NOT NULL,
    hora_entrada TIME   NOT NULL,
    hora_salida  TIME,
    CONSTRAINT ux_asistencias_personal_fecha UNIQUE (personal_id, fecha),
    CONSTRAINT ck_asistencias_rango CHECK (hora_salida IS NULL OR hora_salida > hora_entrada)
);
