CREATE TABLE servicios (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(120)  NOT NULL,
    costo            NUMERIC(10,2) NOT NULL,
    duracion_minutos INTEGER       NOT NULL,
    activo           BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_servicios_costo    CHECK (costo > 0),
    CONSTRAINT ck_servicios_duracion CHECK (duracion_minutos > 0)
);

-- Nombre único sin distinguir mayúsculas, solo entre servicios activos
-- (así un servicio eliminado en el Release 2 no bloquea reutilizar su nombre).
CREATE UNIQUE INDEX ux_servicios_nombre ON servicios (lower(nombre)) WHERE activo;
